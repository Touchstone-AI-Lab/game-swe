local loaded, Queue = pcall(load_submission, "scripts/raiddispatch/queue.lua")
if not loaded or type(Queue) ~= "table" then Queue = {} end
local cases = {}
local function expect(v, m) if not v then error(m or "expectation failed", 0) end end
local function run(name, body) local ok,msg=pcall(body); cases[#cases+1]={name=name,passed=ok,message=ok and "ok" or tostring(msg)} end
local options = { lease_seconds = 10, max_attempts = 2 }
local function fresh()
    expect(type(Queue.new) == "function", "module must export Queue.new")
    return Queue.new(options)
end

run("identifiers, priorities and timestamps are validated", function()
    local queue = fresh()
    expect(queue:enqueue("", "m1", 1, 1).ok == false, "empty request id accepted")
    expect(queue:enqueue("r1", "m1", -1, 1).code == "invalid_request", "negative priority accepted")
    expect(queue:enqueue("r1", "m1", 1.5, 1).code == "invalid_request", "fractional priority accepted")
    expect(queue:enqueue("r1", "m1", 1, 5).ok, "valid enqueue rejected")
    expect(queue:enqueue("r2", "m1", 1, 4).code == "stale_now", "stale timestamp accepted")
    expect(queue:snapshot(5).ready == 1, "a rejected enqueue changed the queue")
end)

run("ready order is priority then sequence and never table order", function()
    local queue = fresh()
    queue:enqueue("low", "m1", 1, 1)
    queue:enqueue("high-a", "m2", 9, 2)
    queue:enqueue("mid", "m3", 5, 3)
    queue:enqueue("high-b", "m4", 9, 4)
    local order = queue:snapshot(5).order
    expect(order[1] == "high-a" and order[2] == "high-b", "equal priorities are not ordered by sequence")
    expect(order[3] == "mid" and order[4] == "low", "priority ordering is wrong")
    expect(queue:enqueue("high-a", "m9", 0, 6).duplicate == true, "duplicate enqueue was not detected")
    expect(queue:snapshot(6).order[1] == "high-a", "a duplicate enqueue moved the request")
end)

run("a request is leased to at most one worker", function()
    local queue = fresh()
    queue:enqueue("r1", "m1", 1, 1)
    queue:enqueue("r2", "m2", 1, 2)
    local first = queue:lease("w1", 3)
    expect(first.ok and first.request_id == "r1" and first.expires_at == 13, "lease expiry is wrong")
    expect(queue:lease("w1", 4).code == "worker_busy", "a worker held two leases")
    local second = queue:lease("w2", 4)
    expect(second.ok and second.request_id == "r2" and second.token ~= first.token, "tokens are not unique")
    expect(queue:lease("w3", 5).code == "empty", "an already leased request was handed out again")
    expect(queue:snapshot(5).leased == 2 and queue:snapshot(5).ready == 0)
end)

run("renew, complete and release consume tokens exactly once", function()
    local queue = fresh()
    queue:enqueue("r1", "m1", 1, 1)
    local lease = queue:lease("w1", 2)
    expect(queue:renew(lease.token, 5).expires_at == 15, "renew did not extend the lease")
    expect(queue:renew("forged", 6).code == "unknown_token", "forged token renewed")
    expect(queue:complete(lease.token, "won", 7).outcome == "won")
    expect(queue:complete(lease.token, "won", 8).ok == false, "complete is not single-use")
    expect(queue:release(lease.token, 9).ok == false, "a completed token was released")
    expect(queue:snapshot(9).completed == 1 and queue:snapshot(9).ready == 0)
end)

run("expiry returns work with its original position and attempt history", function()
    local queue = fresh()
    queue:enqueue("low", "m1", 1, 1)
    queue:enqueue("high", "m2", 9, 2)
    local lease = queue:lease("w1", 3)
    expect(lease.request_id == "high")
    local expired = queue:expire(20)
    expect(expired.expired == 1, "the lease did not expire")
    expect(queue:snapshot(20).order[1] == "high", "expired work lost its priority position")
    expect(queue:renew(lease.token, 21).ok == false, "an expired token was renewed")
    local second = queue:lease("w2", 22)
    expect(second.ok and second.request_id == "high")
    local exhausted = queue:expire(60)
    expect(exhausted.exhausted == 1, "max_attempts was not enforced")
    expect(queue:snapshot(60).order[1] == "low", "an exhausted request stayed dispatchable")
end)

run("snapshots are fresh and never expose worker or member identity", function()
    local queue = fresh()
    queue:enqueue("r1", "m1", 1, 1)
    queue:lease("w1", 2)
    local snapshot = queue:snapshot(3)
    expect(snapshot.members == nil and snapshot.workers == nil and snapshot.leases == nil,
        "snapshot leaked identity maps")
    snapshot.ready = 999
    snapshot.order[1] = "forged"
    local again = queue:snapshot(3)
    expect(again.ready ~= 999, "snapshot is not a fresh table")
    expect(again.order[1] ~= "forged", "snapshot order table is shared with the caller")
end)

run("save and load round-trip order, leases and token sequencing", function()
    local queue = fresh()
    queue:enqueue("low", "m1", 1, 1)
    queue:enqueue("high", "m2", 9, 2)
    local lease = queue:lease("w1", 3)
    expect(type(Queue.load) == "function", "module must export Queue.load")
    local restored = Queue.load(queue:save(5), options)
    expect(restored:snapshot(5).leased == 1 and restored:snapshot(5).ready == 1)
    expect(restored:renew(lease.token, 6).expires_at == 16, "a live lease was lost across reload")
    expect(restored:enqueue("high", "m2", 9, 7).duplicate == true, "deduplication was lost across reload")
    expect(restored:expire(30).expired == 1, "expiry deadlines were lost across reload")
    local reissued = restored:lease("w2", 31)
    expect(reissued.token ~= lease.token, "token sequencing restarted after reload")
end)

return {cases=cases}
