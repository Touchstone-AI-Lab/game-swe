return function(ctx)
    ctx:case("world component is server authoritative", function()
        assert(TheWorld ~= nil and TheWorld.ismastersim, "suite requires master simulation")
        assert(TheWorld.components.campsupplyledger ~= nil, "world is missing campsupplyledger")
    end)

    ctx:case("component delivers configured base-game items", function()
        local component = assert(TheWorld.components.campsupplyledger)
        assert(type(component.Claim) == "function", "component must expose Claim")
        local player = CreateEntity()
        player.entity:AddTransform()
        player:AddComponent("inventory")
        player.userid = "rhenium_server_player"
        local result = component:Claim(player, "server-delivery", "basic")
        assert(type(result) == "table" and result.ok == true, "configured claim failed")
        local has_twigs = player.components.inventory:Has("twigs", 2)
        local has_grass = player.components.inventory:Has("cutgrass", 1)
        assert(has_twigs and has_grass, "claim did not reach real inventory")
        player:Remove()
    end)

    ctx:case("component state survives save and load", function()
        local component = assert(TheWorld.components.campsupplyledger)
        assert(type(component.OnSave) == "function" and type(component.OnLoad) == "function")
        local data = component:OnSave()
        assert(type(data) == "table", "OnSave must return state")
        component:OnLoad(data)
        assert(type(component:OnSave()) == "table", "state was not reloadable")
    end)

    ctx:case("world cycle event is accepted", function()
        local component = assert(TheWorld.components.campsupplyledger)
        local before = component:OnSave()
        TheWorld:PushEvent("ms_cyclecomplete")
        local after = component:OnSave()
        assert(type(before) == "table" and type(after) == "table")
    end)
end
