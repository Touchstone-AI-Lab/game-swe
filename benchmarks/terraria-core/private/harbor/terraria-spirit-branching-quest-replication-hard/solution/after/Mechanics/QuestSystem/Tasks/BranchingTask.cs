using System;
using System.Collections.Generic;
using System.Collections.ObjectModel;
using System.IO;

namespace SpiritMod.Mechanics.QuestSystem.Tasks
{
	public class BranchingTask : QuestTask
	{
		private const byte DataVersion = 1;
		private readonly QuestTask[] _tasks;
		private readonly ReadOnlyCollection<QuestTask> _taskView;

		public override string ModCallName => "##";
		public IEnumerable<QuestTask> Tasks => _taskView;
		internal int TaskCount => _tasks.Length;

		/// <summary>
		/// Stores the index of the completed task in this branching task, so that other clients can properly complete that specific task.<br/>
		/// This stops "completed" <see cref="BranchingTask"/>s from being skipped altogether when synced in <see cref="Quest.RunCompletion(int)"/>.<br/>
		/// This is also the value passed to <see cref="Quest.RunCompletion(int)"/>.
		/// </summary>
		internal byte taskSlotForMP = byte.MaxValue;

		public BranchingTask() : this(Array.Empty<QuestTask>()) { }

		public BranchingTask(params QuestTask[] tasks)
		{
			if (tasks == null)
				throw new ArgumentNullException(nameof(tasks));
			if (tasks.Length > byte.MaxValue)
				throw new ArgumentOutOfRangeException(nameof(tasks), "Branch slot 255 is reserved as the non-branch sentinel.");

			_tasks = (QuestTask[])tasks.Clone();
			for (int i = 0; i < _tasks.Length; i++)
			{
				if (_tasks[i] == null)
					throw new ArgumentException("Branch tasks cannot contain null entries.", nameof(tasks));
			}
			_taskView = Array.AsReadOnly(_tasks);
		}

		internal bool TryGetTask(byte slot, out QuestTask task)
		{
			if (slot == byte.MaxValue || slot >= _tasks.Length)
			{
				task = null;
				return false;
			}
			task = _tasks[slot];
			return true;
		}

		internal bool TryGetSelectedPath(out byte[] path)
		{
			var slots = new List<byte>();
			var visited = new HashSet<BranchingTask>();
			BranchingTask current = this;
			while (true)
			{
				if (!visited.Add(current) || !current.TryGetTask(current.taskSlotForMP, out QuestTask selected))
				{
					path = Array.Empty<byte>();
					return false;
				}

				slots.Add(current.taskSlotForMP);
				if (slots.Count > byte.MaxValue)
				{
					path = Array.Empty<byte>();
					return false;
				}

				if (selected is not BranchingTask nested)
				{
					path = slots.ToArray();
					return true;
				}
				current = nested;
			}
		}

		internal bool TryResolvePath(IReadOnlyList<byte> path, out QuestTask selectedChild, out QuestTask terminal, out BranchingTask[] wrappers)
		{
			selectedChild = null;
			terminal = null;
			wrappers = Array.Empty<BranchingTask>();
			if (path == null || path.Count == 0 || path.Count > byte.MaxValue)
				return false;

			var resolvedWrappers = new List<BranchingTask>();
			var visited = new HashSet<BranchingTask>();
			BranchingTask current = this;
			for (int depth = 0; depth < path.Count; depth++)
			{
				if (!visited.Add(current) || !current.TryGetTask(path[depth], out QuestTask selected))
					return false;

				resolvedWrappers.Add(current);
				if (depth == 0)
					selectedChild = selected;

				if (selected is BranchingTask nested)
				{
					if (depth == path.Count - 1)
						return false;
					current = nested;
					continue;
				}

				if (depth != path.Count - 1)
					return false;
				terminal = selected;
				wrappers = resolvedWrappers.ToArray();
				return true;
			}
			return false;
		}

		internal void CommitPath(IReadOnlyList<byte> path, QuestTask successor)
		{
			BranchingTask current = this;
			for (int depth = 0; depth < path.Count; depth++)
			{
				current.taskSlotForMP = path[depth];
				current.NextTask = successor;
				if (depth + 1 < path.Count)
					current = (BranchingTask)current._tasks[path[depth]];
			}
		}

		public override QuestTask Parse(object[] args) => null;

		public override void AutogeneratedBookText(List<string> lines)
		{
			foreach (QuestTask task in _tasks)
				task.GetBookText(lines);
		}

		public override void AutogeneratedHUDText(List<string> lines)
		{
			foreach (QuestTask task in _tasks)
				task.GetHUDText(lines);
		}

		public override void ResetProgress()
		{
			base.ResetProgress();
			NextTask = null;
			taskSlotForMP = byte.MaxValue;
			foreach (QuestTask task in _tasks)
				task.ResetProgress();
		}

		public override void Activate(Quest fromQuest)
		{
			foreach (QuestTask task in _tasks)
				task.Activate(fromQuest);
			base.Activate(fromQuest);
		}

		public override void Deactivate()
		{
			foreach (QuestTask task in _tasks)
				task.Deactivate();
			base.Deactivate();
		}

		public override bool CheckCompletion()
		{
			for (int slot = 0; slot < _tasks.Length; slot++)
			{
				QuestTask task = _tasks[slot];
				if (!task.CheckCompletion())
					continue;

				taskSlotForMP = (byte)slot;
				NextTask = task.NextTask;
				return true;
			}

			taskSlotForMP = byte.MaxValue;
			NextTask = null;
			return false;
		}

		public override void OnMPSyncTick()
		{
			foreach (QuestTask section in _tasks)
				section.OnMPSyncTick();
		}

		public override void ReadData(BinaryReader reader)
		{
			if (reader == null)
				throw new ArgumentNullException(nameof(reader));

			byte version = reader.ReadByte();
			if (version != DataVersion)
				throw new InvalidDataException($"Unsupported branch task data version {version}.");
			int count = reader.ReadByte();
			byte selectedSlot = reader.ReadByte();
			if (count != _tasks.Length || (selectedSlot != byte.MaxValue && selectedSlot >= count))
				throw new InvalidDataException("Branch topology does not match the saved task data.");

			var completed = new bool[count];
			var payloads = new byte[count][];
			for (int i = 0; i < count; i++)
			{
				int taskId = reader.ReadInt32();
				if (taskId != _tasks[i].TaskID)
					throw new InvalidDataException("Branch child identity does not match the saved task data.");
				completed[i] = reader.ReadBoolean();
				int length = reader.ReadUInt16();
				payloads[i] = reader.ReadBytes(length);
				if (payloads[i].Length != length)
					throw new EndOfStreamException("Branch child payload is truncated.");
			}
			if (reader.BaseStream.Position != reader.BaseStream.Length)
				throw new InvalidDataException("Branch task data has trailing bytes.");

			byte[][] backups = new byte[count][];
			bool[] priorCompleted = new bool[count];
			for (int i = 0; i < count; i++)
			{
				backups[i] = SerializeTask(_tasks[i]);
				priorCompleted[i] = _tasks[i].Completed;
			}

			try
			{
				for (int i = 0; i < count; i++)
				{
					ReadTaskExactly(_tasks[i], payloads[i]);
					_tasks[i].Completed = completed[i];
				}
			}
			catch
			{
				for (int i = 0; i < count; i++)
				{
					ReadTaskExactly(_tasks[i], backups[i]);
					_tasks[i].Completed = priorCompleted[i];
				}
				throw;
			}

			taskSlotForMP = selectedSlot;
			NextTask = TryGetTask(selectedSlot, out QuestTask selected) ? selected.NextTask : null;
		}

		public override void WriteData(BinaryWriter writer)
		{
			if (writer == null)
				throw new ArgumentNullException(nameof(writer));

			using var stream = new MemoryStream();
			using (var frame = new BinaryWriter(stream, System.Text.Encoding.UTF8, true))
			{
				frame.Write(DataVersion);
				frame.Write((byte)_tasks.Length);
				frame.Write(taskSlotForMP);
				foreach (QuestTask task in _tasks)
				{
					byte[] payload = SerializeTask(task);
					if (payload.Length > ushort.MaxValue)
						throw new InvalidDataException("Branch child task data exceeds 65535 bytes.");
					frame.Write(task.TaskID);
					frame.Write(task.Completed);
					frame.Write((ushort)payload.Length);
					frame.Write(payload);
				}
			}
			writer.Write(stream.ToArray());
		}

		private static byte[] SerializeTask(QuestTask task)
		{
			using var stream = new MemoryStream();
			using (var writer = new BinaryWriter(stream, System.Text.Encoding.UTF8, true))
				task.WriteData(writer);
			return stream.ToArray();
		}

		private static void ReadTaskExactly(QuestTask task, byte[] payload)
		{
			using var stream = new MemoryStream(payload, writable: false);
			using var reader = new BinaryReader(stream);
			task.ReadData(reader);
			if (stream.Position != stream.Length)
				throw new InvalidDataException("Branch child did not consume its complete payload.");
		}
	}
}
